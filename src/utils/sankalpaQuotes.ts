/**
 * Returns a daily quote deterministically based on date (YYYY-MM-DD),
 * ensuring the quote stays consistent throughout the entire calendar day for all users.
 */
export function getDailySankalpa(targetDate = new Date()): SankalpaQuote {
  const dayOfYear = Math.floor(
    (Date.UTC(targetDate.getFullYear(), targetDate.getMonth(), targetDate.getDate()) -
      Date.UTC(targetDate.getFullYear(), 0, 0)) /
      (24 * 60 * 60 * 1000)
  );
  const index = Math.abs(dayOfYear) % CULTURALLY_RELEVANT_SANKALPAS.length;
  const quote = CULTURALLY_RELEVANT_SANKALPAS[index];

  const dateKey = targetDate.toISOString().slice(0, 10);
  return {
    ...quote,
    dateKey,
  };
}

/**
 * Returns a random quote (excluding the current one if specified)
 */
export function getRandomSankalpa(excludeId?: string): SankalpaQuote {
  const pool = excludeId
    ? CULTURALLY_RELEVANT_SANKALPAS.filter((item) => item.id !== excludeId)
    : CULTURALLY_RELEVANT_SANKALPAS;
  const randomIndex = Math.floor(Math.random() * pool.length);
  return pool[randomIndex] || CULTURALLY_RELEVANT_SANKALPAS[0];
}
